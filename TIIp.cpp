using namespace std; // Используем стандартное пространство имён

int main() { // Начало программы
    string x; // Начальная последовательность
    int n; // Номер нужного элемента
    cin >> x >> n; // Вводим данные

    for (int k = 1; k < n; k++) { // Повторяем построение нужное число раз
        string s = ""; // Создаём строку для нового элемента

        for (int i = 0; i < x.size(); i++) { // Перебираем цифры строки
            int count = 1; // Текущая цифра уже посчитана

            while (i + 1 < x.size() && x[i] == x[i + 1]) { // Проверяем следующую цифру
                count++; // Увеличиваем количество одинаковых цифр
                i++; // Переходим к следующей цифре
            }

            s += to_string(count); // Добавляем количество
            s += x[i]; // Добавляем цифру
        }

        x = s; // Обновляем последовательность
    }

    cout << x; // Выводим ответ
    return 0; // Завершаем программу
}