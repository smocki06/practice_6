#include <iostream> // Подключаем ввод и вывод
using namespace std; // Используем стандартное пространство имён

int main() { // Начало программы
    int n, m, w; // Количество строк, столбцов и грибов
    cin >> n >> m >> w; // Вводим размеры поля и число грибов

    char a[32][32]; // Создаём массив для карты

    for (int i = 0; i < n; i++) { // Перебираем строки поля
        for (int j = 0; j < m; j++) { // Перебираем столбцы поля
            a[i][j] = '0'; // Пока во всех клетках ноль
        }
    }

    for (int i = 0; i < w; i++) { // Вводим координаты всех грибов
        int x, y; // Координаты гриба
        cin >> x >> y; // Считываем строку и столбец
        a[x - 1][y - 1] = '*'; // Ставим гриб на карте
    }

    for (int i = 0; i < n; i++) { // Перебираем строки для вывода
        for (int j = 0; j < m; j++) { // Перебираем столбцы для вывода
            if (a[i][j] == '*') { // Если в клетке гриб
                cout << '*'; // Выводим звёздочку
            }
            else { // Если гриба нет
                int k = 0; // Счётчик соседних грибов

                for (int x = i - 1; x <= i + 1; x++) { // Проверяем соседние строки
                    for (int y = j - 1; y <= j + 1; y++) { // Проверяем соседние столбцы
                        if (x >= 0 && x < n && y >= 0 && y < m) { // Проверяем границы поля
                            if (a[x][y] == '*') { // Если соседняя клетка с грибом и мы не вышли за пределы карты
                                k++; // Увеличиваем счётчик
                            }
                        }
                    }
                }

                cout << k; // Выводим количество соседних грибов
            }
        }
        cout << endl; // Переходим на следующую строку
    }

    return 0; // Завершаем программу
}


